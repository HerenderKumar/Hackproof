"""The run jobs, `final_run` and `self_check_run` (sections 11.6 and 12.1 to 12.3).

A run never reads the live repository: it extracts the snapshot's archive into
`ARTIFACT_DIR/work/<attempt_id>/src`, builds it, and runs the image in the sandbox. Logs are
kept under `ARTIFACT_DIR/runs/<attempt_id>/`; the work directory is deleted however the run
ends. The image is kept until `make prune`.

A build that fails and an app that does not start are results, recorded in `run_results`
like any other (section 11.3); only infrastructure errors propagate, so the job is retried.
`run_results` has no column for why a build failed, so a skipped startup carries the reason:
"not started: build timed out".

The startup check is generated by code from the team's `health_path` (section 6.2); the
claims' specs that run with it are chosen by `worker/run_specs.py`. Their results become
`test_results` (`worker/results.py`), written with `run_results` in one transaction and at
most once per attempt.
"""

import asyncio
import shutil
from collections.abc import Awaitable, Callable
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Any, Literal
from uuid import UUID

from sqlalchemy.dialects.postgresql import insert

from core import queue
from core.clock import Clock
from core.db import models
from core.db.engine import Sessions
from core.logging import get_logger
from core.settings import Settings
from core.snapshots import extract_archive
from worker.build import BuildResult, build_image
from worker.door import DoorRun, DoorTerms
from worker.lanes import Handler, Outcome
from worker.results import result_rows
from worker.run_specs import RunPlan, final_run_plan, self_check_plan
from worker.runtime import ContainerRuntime
from worker.sandbox import RunOutcome, SandboxLimits, run_sandboxed

log = get_logger()

RUN_KINDS = ("final_run", "self_check_run")

Build = Callable[..., Awaitable[BuildResult]]
Run = Callable[..., Awaitable[RunOutcome]]


@dataclass(frozen=True)
class RunReport:
    build: BuildResult
    run: RunOutcome | None  # None when the build failed


def startup_spec(health_path: str) -> dict[str, Any]:
    """The startup check's spec (section 14.3). Made by code, never by the model."""
    return {
        "kind": "startup",
        "claim_type": "startup",
        "steps": [{"health_path": health_path}],
        "practice_cases": [],
        "final_cases": [],
    }


async def build_and_run(
    *,
    archive_path: Path,
    archive_sha256: str,
    team_id: UUID,
    attempt_id: UUID,
    mode: Literal["practice", "final"],
    specs: list[dict[str, Any]],
    artifact_dir: Path,
    runtime: ContainerRuntime,
    build_timeout_s: float,
    buildkit_host: str,
    railpack_version: str,
    limits: SandboxLimits,
    build: Build = build_image,
    run: Run = run_sandboxed,
    door_terms: DoorTerms | None = None,
) -> RunReport:
    work = artifact_dir / "work" / str(attempt_id)
    logs = artifact_dir / "runs" / str(attempt_id)
    try:
        await asyncio.to_thread(extract_archive, archive_path, archive_sha256, work / "src")
        built = await build(
            work / "src",
            work / "build",
            team_id=team_id,
            attempt_id=attempt_id,
            log_path=logs / "build.log",
            runtime=runtime,
            timeout_s=build_timeout_s,
            buildkit_host=buildkit_host,
            railpack_version=railpack_version,
        )
        if built.status != "ok" or built.image is None:
            return RunReport(built, None)
        door = None
        if door_terms is not None:
            door = DoorRun.make(
                door_terms, attempt_id=attempt_id, team_id=team_id, mode=mode, run_dir=work / "run"
            )
        extra = {"door": door} if door is not None else {}
        outcome = await run(
            runtime,
            image=built.image,
            attempt_id=attempt_id,
            run_dir=work / "run",
            mode=mode,
            specs=specs,
            limits=limits,
            app_log_path=logs / "app.log",
            **extra,
        )
        return RunReport(built, outcome)
    finally:
        await asyncio.to_thread(shutil.rmtree, work, ignore_errors=True)


def make_run_handler(
    sessions: Sessions,
    runtime: ContainerRuntime,
    settings: Settings,
    clock: Clock,
    *,
    build: Build = build_image,
    run: Run = run_sandboxed,
) -> Handler:
    limits = SandboxLimits.from_settings(settings)
    door_terms = DoorTerms.from_settings(settings)

    async def run_job(job: queue.Job) -> Outcome | None:
        found = await _load(sessions, job)
        if isinstance(found, Outcome):
            return found
        snapshot, team, plan = found

        started_at = clock.now()
        report = await build_and_run(
            archive_path=Path(snapshot.archive_path),
            archive_sha256=snapshot.archive_sha256,
            team_id=team.id,
            attempt_id=job.attempt_id,
            mode=plan.mode,
            specs=[startup_spec(team.health_path), *plan.runnable],
            artifact_dir=settings.artifact_dir,
            runtime=runtime,
            build_timeout_s=settings.build_timeout_s,
            buildkit_host=settings.buildkit_host,
            railpack_version=settings.railpack_version,
            limits=limits,
            build=build,
            run=run,
            door_terms=door_terms,
        )
        await _record(sessions, job, report, plan, started_at, clock.now())
        return None

    return run_job


async def _load(
    sessions: Sessions, job: queue.Job
) -> tuple[models.Snapshot, models.Team, RunPlan] | Outcome:
    """The snapshot a run builds, its team, and the specs it carries.

    A final run reaches its snapshot through its submission and carries the specs the
    submission pinned; a self-check carries the specs its payload lists, or the current ones.
    """
    async with sessions() as session:
        snapshot_id = job.snapshot_id
        submission = None
        if job.kind == "final_run":
            if job.submission_id is not None:
                submission = await session.get(models.Submission, job.submission_id)
            if submission is None:
                return Outcome("validation", "final_run needs a submission")
            snapshot_id = submission.snapshot_id
        snapshot = None
        if snapshot_id is not None:
            snapshot = await session.get(models.Snapshot, snapshot_id)
        if snapshot is None:
            return Outcome("validation", f"{job.kind} needs a snapshot")
        team = await session.get(models.Team, snapshot.team_id)
        if team is None:
            return Outcome("validation", f"{job.kind} needs a team")
        if submission is not None:
            plan = await final_run_plan(session, submission)
            if isinstance(plan, Outcome):
                return plan
        else:
            listed = job.payload.get("spec_ids")
            spec_ids = [UUID(str(spec_id)) for spec_id in listed] if listed else None
            plan = await self_check_plan(session, snapshot.team_id, spec_ids)
        return snapshot, team, plan


async def _record(
    sessions: Sessions,
    job: queue.Job,
    report: RunReport,
    plan: RunPlan,
    started_at: datetime,
    finished_at: datetime,
) -> None:
    """Write `run_results` and its `test_results` together, at most once per attempt."""

    built, ran = report.build, report.run
    if ran is None:
        startup_status, startup_detail = "skipped", f"not started: {built.detail}"
        flags_used: dict[str, Any] = {}
    else:
        startup_status, startup_detail = ran.startup_status, ran.startup_detail
        flags_used = {**ran.flags_used, **({"run_timed_out": True} if ran.timed_out else {})}

    rows = result_rows(report, plan)
    async with sessions.begin() as session:
        written = await session.scalar(
            insert(models.RunResult)
            .values(
                job_id=job.id,
                attempt_id=job.attempt_id,
                build_status=built.status,
                build_exit_code=built.exit_code,
                build_method=built.method,
                startup_status=startup_status,
                startup_detail=startup_detail,
                image_digest=built.image_digest,
                build_config=built.build_config,
                flags_used=flags_used,
                build_log_path=str(built.log_path),
                app_log_path=str(ran.app_log_path) if ran else None,
                started_at=started_at,
                finished_at=finished_at,
            )
            .on_conflict_do_nothing(index_elements=["job_id", "attempt_id"])
            .returning(models.RunResult.id)
        )
        if written is not None and rows:  # a repeat of this attempt adds nothing
            await session.execute(
                insert(models.TestResult),
                [{"job_id": job.id, "attempt_id": job.attempt_id, **row} for row in rows],
            )
    log.info(
        "run_recorded",
        build_status=built.status,
        build_method=built.method,
        startup_status=startup_status,
        root_fallback=flags_used.get("root_fallback"),
        port=flags_used.get("port"),
        tests=len(rows),
        verdicts=sorted({row["verdict"] for row in rows}),
    )
