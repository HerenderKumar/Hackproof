"""The startup check (section 6.2): is the team's app answering HTTP?

Generated by code, never by the model. Every second, for up to `startup_timeout_s`, ask
`base_url + health_path` on each candidate port in turn. Any status below 500 means the app is
up, and the first port that answers is the one the tests use.
"""

import time
from collections.abc import Callable
from typing import Any
from urllib.parse import urlsplit

import httpx

INTERVAL_S = 1.0
PROBE_TIMEOUT_S = 2.0


class ProbeFailed(Exception):
    """No HTTP answer at all; the message says why (refused, timed out, ...)."""


Probe = Callable[[str], int]


def http_probe(url: str) -> int:
    """One GET without following redirects. Returns the status or raises `ProbeFailed`."""
    try:
        return httpx.get(url, timeout=PROBE_TIMEOUT_S, follow_redirects=False).status_code
    except httpx.TimeoutException:
        raise ProbeFailed("timed out") from None
    except httpx.HTTPError as exc:
        raise ProbeFailed((str(exc) or type(exc).__name__)[:200]) from None


def url_for(base_url: str, port: int, path: str) -> str:
    parts = urlsplit(base_url)
    return f"{parts.scheme}://{parts.hostname}:{port}{path}"


def check_startup(
    base_url: str,
    candidate_ports: list[int],
    health_path: str,
    *,
    timeout_s: float,
    probe: Probe = http_probe,
    monotonic: Callable[[], float] = time.monotonic,
    sleep: Callable[[float], None] = time.sleep,
) -> dict[str, Any]:
    started = monotonic()
    deadline = started + timeout_s
    round_start = started
    last_reason = "no answer"
    server_error: str | None = None

    def elapsed_ms() -> int:
        return round((monotonic() - started) * 1000)

    while True:
        for port in candidate_ports:
            try:
                status = probe(url_for(base_url, port, health_path))
            except ProbeFailed as exc:
                last_reason = str(exc)
                continue
            if status < 500:
                seconds = monotonic() - started
                return {
                    "status": "ok",
                    "detail": f"HTTP {status} after {seconds:.1f}s on port {port}",
                    "port": port,
                    "elapsed_ms": elapsed_ms(),
                }
            server_error = f"HTTP {status} on port {port}"

        round_start += INTERVAL_S
        if round_start >= deadline:
            sleep(max(0.0, deadline - monotonic()))
            break
        sleep(max(0.0, round_start - monotonic()))

    limit = f"within {timeout_s:g} s"
    if server_error is not None:
        detail = f"no answer below HTTP 500 {limit} (last: {server_error})"
    else:
        ports = ", ".join(str(p) for p in candidate_ports)
        where = f"port {ports}" if len(candidate_ports) == 1 else f"ports {ports}"
        detail = f"nothing answered on {where} {limit} (last: {last_reason})"
    return {"status": "fail", "detail": detail, "port": None, "elapsed_ms": elapsed_ms()}
